"""Render every character to sprite sheets in HellKnight/Sprites and emit SpriteData.swift.

Usage: python build.py <repo root>
"""
import os
import sys
from render import build_sheet
import knight, imp, archer, brute, wisp, priest, boss

ROOT = sys.argv[1]
OUT = os.path.join(ROOT, "HellKnight", "Sprites")
os.makedirs(OUT, exist_ok=True)

# name, draw fn, anims, frame w, frame h (points), ground offset, render scale
SHEETS = []
for wpn in ("blade", "pike", "fists"):
    SHEETS.append((f"knight_{wpn}", (lambda w: (lambda pen, P: knight.draw(pen, P, w)))(wpn), knight.anims_for(wpn),
                   180, 140, 16, 2.0))
SHEETS += [
    ("imp", imp.draw, imp.ANIMS, 110, 90, 12, 2.0),
    ("archer", archer.draw, archer.ANIMS, 110, 100, 10, 2.0),
    ("brute", brute.draw, brute.ANIMS, 140, 130, 10, 2.0),
    ("wisp", wisp.draw, wisp.ANIMS, 80, 80, 10, 2.0),
    ("priest", priest.draw, priest.ANIMS, 110, 110, 10, 2.0),
]
for d in range(3):
    SHEETS.append((f"boss{d}", boss.make_draw(d), boss.ANIMS, 220, 230, 16, 1.6))

swift = ["// Generated by tools/spritegen/build.py — do not edit by hand.", "import CoreGraphics", "",
         "enum SpriteData {"]
for name, draw, anims, w, h, ground, sc in SHEETS:
    cols = max(n for _, n, _, _ in anims)
    sheet, meta = build_sheet(anims, draw, w, h, ground, sc, cols=cols)
    path = os.path.join(OUT, f"{name}.png")
    sheet.save(path, optimize=True)
    print(f"{name}: {sheet.size[0]}x{sheet.size[1]} px, {os.path.getsize(path) // 1024} KB")
    entries = ", ".join(f'"{a}": AnimInfo(row: {r}, count: {n}, loops: {"true" if lp else "false"})'
                        for (a, r, n, lp) in meta)
    swift.append(f'    static let {name} = SheetInfo(file: "{name}", frame: CGSize(width: {w}, height: {h}), '
                 f'ground: {ground}, cols: {cols}, rows: {len(anims)},')
    swift.append(f'                                  anims: [{entries}])')
swift.append("}")
with open(os.path.join(ROOT, "HellKnight", "Sources", "SpriteData.swift"), "w") as f:
    f.write("\n".join(swift) + "\n")
